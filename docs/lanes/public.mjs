const byCode = Object.fromEntries(streams.map((s) => [s.code, s]))

const stations = (s) =>
  s.steps.map((st, i) => ({
    n: i + 1,
    label: st.label,
    note: st.note ?? null,
    refuse: st.refuse ?? null,
    pending: Boolean(st.hollow),
  }))

const diagram = (code, seen) => {
  const s = byCode[code]
  if (!s) throw new Error(`no stream with code ${code}`)
  return {
    code: s.code,
    name: s.name,
    aria: s.aria,
    caption: CAPTIONS[s.code] ?? s.caption,
    svg: svg({ lanes: s.lanes, steps: s.steps, arrows: s.arrows },
             { id: `${seen}-${s.id}`, aria: s.aria, laneH: 92 }),
    stations: stations(s),
  }
}

const pages = PAGES.map((p) => ({
  slug: p.slug,
  title: p.title,
  eyebrow: p.eyebrow,
  lede: p.lede,
  diagrams: p.codes.map((c) => diagram(c, p.slug)),
}))

const header = `/**
 * GENERATED by docs/lanes/public.mjs — do not edit by hand.
 *
 * Re-run \`node docs/lanes/public.mjs\` after changing docs/lanes/streams.mjs.
 * __tests__/invariants/flows-public.test.ts holds the leak guard over this file.
 */
`

const types = `
export interface FlowStation {
  /** Its number in the drawing, in reading order. */
  n: number
  label: string
  note: string | null
  /** A refusal, said in a sentence, where the flow blocks rather than warns. */
  refuse: string | null
  /** A station the operating model names that the build does not yet do. */
  pending: boolean
}

export interface FlowDiagram {
  code: string
  name: string
  aria: string
  caption: string
  /** Inline SVG. Generated here, committed, never user input. */
  svg: string
  stations: FlowStation[]
}

export interface FlowPage {
  slug: string
  title: string
  eyebrow: string
  lede: string
  diagrams: FlowDiagram[]
}
`

writeFileSync(
  new URL('../../src/lib/flows.generated.ts', import.meta.url),
  `${header}${types}\nexport const FLOW_PAGES: FlowPage[] = ${JSON.stringify(pages, null, 2)}\n`,
)

const n = pages.reduce((a, p) => a + p.diagrams.length, 0)
console.log(`${pages.length} pages, ${n} drawings → src/lib/flows.generated.ts`)
