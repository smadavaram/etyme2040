/**
 * The public flow pages, from the same data as the party documents.
 *
 * `build-all.mjs` draws the operating model for the founder and for a buyer
 * who knows another system's words, so every stream there carries a
 * trade-language table naming that system. None of that may appear on
 * etyme.com: `lib/positioning` refuses a real company on a marketing page,
 * severity WRONG, and the hero already had two incumbents struck from it.
 *
 * So this render drops the tables entirely and keeps what a scan of every
 * field showed to be clean on its own: the diagrams, the stream names, the
 * aria labels, and all 84 station labels and notes. Four captions named a
 * competitor and are rewritten below, keeping every fact in them.
 *
 *     node docs/lanes/public.mjs   → src/lib/flows.generated.ts
 *
 * A leak guard in __tests__/invariants/flows-public.test.ts re-runs the same
 * regex over the generated file, so a later caption edit cannot quietly put a
 * competitor's name on the marketing site.
 */
import { writeFileSync } from 'node:fs'
import { streams, svg } from './streams.mjs'

/** The four captions that named another system, rewritten fact for fact. */
